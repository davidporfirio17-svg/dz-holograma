import Foundation

enum NyxelStringShield {
    private static let xorKey: [UInt8] = [0x4E, 0x79, 0x78, 0x65, 0x6C, 0x53, 0x68, 0x69, 0x65, 0x6C, 0x64, 0x21]

    static func reveal(_ encrypted: [UInt8]) -> String {
        var out = [UInt8](repeating: 0, count: encrypted.count)
        for i in 0..<encrypted.count {
            out[i] = encrypted[i] ^ xorKey[i % xorKey.count]
        }
        return String(bytes: out, encoding: .utf8) ?? ""
    }

    static var workerHost: String {
        reveal([0x2a, 0x03, 0x55, 0x0d, 0x03, 0x3f, 0x07, 0x0e, 0x17, 0x0d, 0x09, 0x40, 0x60, 0x1d, 0x19, 0x13, 0x05, 0x37, 0x18, 0x06, 0x17, 0x0a, 0x0d, 0x53, 0x27, 0x16, 0x49, 0x52, 0x42, 0x24, 0x07, 0x1b, 0x0e, 0x09, 0x16, 0x52, 0x60, 0x1d, 0x1d, 0x13])
    }

    static var pathCheck: String {
        reveal([0x61, 0x1a, 0x10, 0x00, 0x0f, 0x38])
    }

    static var pathAppConfig: String {
        reveal([0x61, 0x18, 0x08, 0x15, 0x41, 0x30, 0x07, 0x07, 0x03, 0x05, 0x03])
    }

    static var pathConsumeMode: String {
        reveal([0x61, 0x1a, 0x17, 0x0b, 0x1f, 0x26, 0x05, 0x0c, 0x48, 0x01, 0x0b, 0x45, 0x2b])
    }

    static var pathAvatar: String {
        reveal([0x61, 0x18, 0x0e, 0x04, 0x18, 0x32, 0x1a, 0x46])
    }

    static var contentTypeJSON: String {
        reveal([0x2f, 0x09, 0x08, 0x09, 0x05, 0x30, 0x09, 0x1d, 0x0c, 0x03, 0x0a, 0x0e, 0x24, 0x0a, 0x17, 0x0b])
    }

    static var headerKey: String {
        reveal([0x16, 0x54, 0x3c, 0x3f, 0x41, 0x18, 0x0d, 0x10])
    }

    static var headerHWID: String {
        reveal([0x16, 0x54, 0x3c, 0x3f, 0x41, 0x1b, 0x3f, 0x20, 0x21])
    }

    static var headerInstallation: String {
        reveal([0x16, 0x54, 0x3c, 0x3f, 0x41, 0x1a, 0x06, 0x1a, 0x11, 0x0d, 0x08, 0x4d, 0x2f, 0x0d, 0x11, 0x0a, 0x02])
    }

    static var headerBuild: String {
        reveal([0x16, 0x54, 0x3c, 0x3f, 0x41, 0x11, 0x1d, 0x00, 0x09, 0x08])
    }

    static var headerSession: String {
        reveal([0x16, 0x54, 0x3c, 0x3f, 0x41, 0x00, 0x0d, 0x1a, 0x16, 0x05, 0x0b, 0x4f])
    }

    static func workerURL(_ host: String, path: String) -> URL? {
        URL(string: "https://" + host + path)
    }
}
